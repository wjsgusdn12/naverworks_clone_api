-- API 대시보드의 1시간 요약(일주일 그래프용). 최근 24시간 5분 단위 기록은 Redis·메모리에 두고,
-- 오래 볼 기록만 1시간 단위로 합쳐 DB에 남겨 서버·Redis가 재시작돼도 유지되게 함.
-- endpoint가 '*'인 행은 그 시간의 전체 합계. latency_0~8은 응답 시간 구간별 개수(p95 계산용).
-- 서버 1·2가 같은 행에 "더하기"로 기록하므로 (hour_start, endpoint)는 하나만 존재.
CREATE TABLE api_metric_hourly (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hour_start TIMESTAMP WITH TIME ZONE NOT NULL,
    endpoint VARCHAR(300) NOT NULL,
    request_count BIGINT NOT NULL DEFAULT 0,
    client_errors BIGINT NOT NULL DEFAULT 0,
    server_errors BIGINT NOT NULL DEFAULT 0,
    duration_sum_ms BIGINT NOT NULL DEFAULT 0,
    latency_0 BIGINT NOT NULL DEFAULT 0,
    latency_1 BIGINT NOT NULL DEFAULT 0,
    latency_2 BIGINT NOT NULL DEFAULT 0,
    latency_3 BIGINT NOT NULL DEFAULT 0,
    latency_4 BIGINT NOT NULL DEFAULT 0,
    latency_5 BIGINT NOT NULL DEFAULT 0,
    latency_6 BIGINT NOT NULL DEFAULT 0,
    latency_7 BIGINT NOT NULL DEFAULT 0,
    latency_8 BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_api_metric_hourly UNIQUE (hour_start, endpoint)
);

-- 기간 조회(최근 7일 합계 행)에 맞춘 인덱스.
CREATE INDEX idx_api_metric_hourly_endpoint_hour ON api_metric_hourly (endpoint, hour_start);
