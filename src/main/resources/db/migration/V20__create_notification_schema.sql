-- 구성원별 서비스 알림(메시지·주소록·시스템)을 저장. 최근 30일 조회와 읽음 처리에 사용.
CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membership_id BIGINT NOT NULL,
    category VARCHAR(20) NOT NULL,
    title VARCHAR(200) NOT NULL,
    body VARCHAR(500) NOT NULL,
    link_path VARCHAR(300),
    read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notification_membership FOREIGN KEY (membership_id) REFERENCES membership (id),
    CONSTRAINT ck_notification_category CHECK (category IN ('MESSAGE', 'ADDRESS_BOOK', 'SYSTEM'))
);

-- 구성원의 최근 알림을 최신순으로 읽는 조회에 맞춘 인덱스.
CREATE INDEX idx_notification_membership_created ON notification (membership_id, created_at DESC);
