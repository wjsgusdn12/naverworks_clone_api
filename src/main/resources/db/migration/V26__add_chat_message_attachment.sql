-- 메시지 첨부(사진·파일). 메시지 하나에 첨부 하나. 실제 파일은 서버 디스크에 두고 위치 키만 기록.
-- 전달한 메시지는 같은 파일을 가리키는 첨부 행을 새로 만들어 연결.
CREATE TABLE chat_message_attachment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_message_id BIGINT NOT NULL,
    chat_room_id BIGINT NOT NULL,
    kind VARCHAR(10) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    storage_key VARCHAR(100) NOT NULL,
    width INTEGER NULL,
    height INTEGER NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_chat_message_attachment_message FOREIGN KEY (chat_message_id) REFERENCES chat_message (id),
    CONSTRAINT fk_chat_message_attachment_room FOREIGN KEY (chat_room_id) REFERENCES chat_room (id),
    CONSTRAINT uk_chat_message_attachment_message UNIQUE (chat_message_id),
    CONSTRAINT ck_chat_message_attachment_kind CHECK (kind IN ('IMAGE', 'FILE'))
);

-- 방 상세의 사진·파일 모아보기(종류별 최신순)에 맞춘 인덱스.
CREATE INDEX idx_chat_message_attachment_room ON chat_message_attachment (chat_room_id, kind, id);
