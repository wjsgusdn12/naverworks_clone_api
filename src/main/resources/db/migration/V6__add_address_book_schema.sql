-- 주소록에서 사용할 부서 활성 상태와 구성원 프로필 정보를 추가.
ALTER TABLE department ADD COLUMN enabled BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE job_grade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    name VARCHAR(50) NOT NULL,
    sort_order INTEGER NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_job_grade_company FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT uk_job_grade_company_name UNIQUE (company_id, name),
    CONSTRAINT uk_job_grade_company_order UNIQUE (company_id, sort_order)
);

ALTER TABLE membership ADD COLUMN job_title VARCHAR(100);
ALTER TABLE membership ADD COLUMN job_grade_id BIGINT;
ALTER TABLE membership ADD COLUMN phone_number VARCHAR(30);
ALTER TABLE membership ADD COLUMN hired_at DATE;
ALTER TABLE membership ADD COLUMN away_until TIMESTAMP WITH TIME ZONE;
ALTER TABLE membership ADD CONSTRAINT fk_membership_job_grade
    FOREIGN KEY (job_grade_id) REFERENCES job_grade (id);

-- 즐겨찾기는 각 사용자가 같은 회사의 다른 구성원을 독립적으로 보관.
CREATE TABLE member_favorite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_membership_id BIGINT NOT NULL,
    target_membership_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_member_favorite_owner FOREIGN KEY (owner_membership_id) REFERENCES membership (id),
    CONSTRAINT fk_member_favorite_target FOREIGN KEY (target_membership_id) REFERENCES membership (id),
    CONSTRAINT uk_member_favorite_owner_target UNIQUE (owner_membership_id, target_membership_id),
    CONSTRAINT ck_member_favorite_not_self CHECK (owner_membership_id <> target_membership_id)
);

-- 주소록 그룹과 그룹 구성원. 메신저 채팅방 도메인과는 분리.
CREATE TABLE contact_group (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    master_membership_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_contact_group_company FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_contact_group_master FOREIGN KEY (master_membership_id) REFERENCES membership (id),
    CONSTRAINT uk_contact_group_company_name UNIQUE (company_id, name)
);

CREATE TABLE contact_group_member (
    contact_group_id BIGINT NOT NULL,
    membership_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (contact_group_id, membership_id),
    CONSTRAINT fk_contact_group_member_group FOREIGN KEY (contact_group_id) REFERENCES contact_group (id),
    CONSTRAINT fk_contact_group_member_membership FOREIGN KEY (membership_id) REFERENCES membership (id)
);

CREATE INDEX idx_job_grade_company_id ON job_grade (company_id);
CREATE INDEX idx_member_favorite_owner_id ON member_favorite (owner_membership_id);
CREATE INDEX idx_contact_group_company_id ON contact_group (company_id);
CREATE INDEX idx_contact_group_member_membership_id ON contact_group_member (membership_id);

-- 회사별 기본 직급은 관리 화면에서 이후 수정·비활성화할 수 있음.
INSERT INTO job_grade (company_id, name, sort_order)
SELECT company.id, grade.name, grade.sort_order
FROM company
CROSS JOIN (
    VALUES
        ('사원', 1), ('주임', 2), ('대리', 3), ('과장', 4),
        ('차장', 5), ('부장', 6), ('부대표', 7), ('대표', 8)
) AS grade(name, sort_order);
