-- 메시지 이모지 리액션. 한 사람이 한 메시지에 같은 이모지를 두 번 누를 수 없도록 유니크 제약.
CREATE TABLE chat_message_reaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_message_id BIGINT NOT NULL,
    membership_id BIGINT NOT NULL,
    emoji VARCHAR(40) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chat_message_reaction_message FOREIGN KEY (chat_message_id) REFERENCES chat_message (id),
    CONSTRAINT fk_chat_message_reaction_membership FOREIGN KEY (membership_id) REFERENCES membership (id),
    CONSTRAINT uk_chat_message_reaction UNIQUE (chat_message_id, membership_id, emoji)
);

-- 메시지 목록을 그릴 때 메시지 ID 묶음으로 집계하는 조회에 맞춘 인덱스.
CREATE INDEX idx_chat_message_reaction_message ON chat_message_reaction (chat_message_id);
