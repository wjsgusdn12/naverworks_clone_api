CREATE TABLE chat_room (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    room_type VARCHAR(20) NOT NULL,
    name VARCHAR(100),
    owner_membership_id BIGINT,
    ended_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chat_room_company FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_chat_room_owner FOREIGN KEY (owner_membership_id) REFERENCES membership (id),
    CONSTRAINT ck_chat_room_type CHECK (room_type IN ('DIRECT', 'GROUP')),
    CONSTRAINT ck_chat_room_group_name CHECK ((room_type = 'DIRECT' AND name IS NULL) OR (room_type = 'GROUP' AND name IS NOT NULL))
);

CREATE TABLE chat_room_member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_room_id BIGINT NOT NULL,
    membership_id BIGINT NOT NULL,
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at TIMESTAMP WITH TIME ZONE,
    last_read_message_id BIGINT,
    CONSTRAINT fk_chat_room_member_room FOREIGN KEY (chat_room_id) REFERENCES chat_room (id),
    CONSTRAINT fk_chat_room_member_membership FOREIGN KEY (membership_id) REFERENCES membership (id),
    CONSTRAINT uk_chat_room_member_room_membership UNIQUE (chat_room_id, membership_id)
);

CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_room_id BIGINT NOT NULL,
    sender_membership_id BIGINT NOT NULL,
    content VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chat_message_room FOREIGN KEY (chat_room_id) REFERENCES chat_room (id),
    CONSTRAINT fk_chat_message_sender FOREIGN KEY (sender_membership_id) REFERENCES membership (id)
);

CREATE INDEX idx_chat_room_company_id ON chat_room (company_id);
CREATE INDEX idx_chat_room_member_membership_active ON chat_room_member (membership_id, left_at);
CREATE INDEX idx_chat_message_room_id_id ON chat_message (chat_room_id, id);
