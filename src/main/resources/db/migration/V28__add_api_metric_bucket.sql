-- API 대시보드의 5분 칸(이번 시간·오늘 그래프용). 서버·Redis가 재시작돼도 남도록 DB에 보관.
-- 칸 자리(slot)는 300개(25시간분)로 고정하고 돌려 씀: 5분 칸 번호(bucket) % 300 자리에,
-- 25시간 지난 옛 기록이 있으면 새 기록으로 덮어씀(지우지 않으므로 행 수가 늘지 않음).
-- endpoint가 '*'인 행은 그 칸의 전체 합계. latency_0~8은 응답 시간 구간별 개수(p95 계산용).
-- 서버 1·2가 같은 행에 "더하기"로 기록하므로 (slot, endpoint)는 하나만 존재.
CREATE TABLE api_metric_bucket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot INTEGER NOT NULL,
    endpoint VARCHAR(300) NOT NULL,
    bucket BIGINT NOT NULL,
    request_count BIGINT NOT NULL DEFAULT 0,
    client_errors BIGINT NOT NULL DEFAULT 0,
    server_errors BIGINT NOT NULL DEFAULT 0,
    duration_sum_ms BIGINT NOT NULL DEFAULT 0,
    latency_0 BIGINT NOT NULL DEFAULT 0,
    latency_1 BIGINT NOT NULL DEFAULT 0,
    latency_2 BIGINT NOT NULL DEFAULT 0,
    latency_3 BIGINT NOT NULL DEFAULT 0,
    latency_4 BIGINT NOT NULL DEFAULT 0,
    latency_5 BIGINT NOT NULL DEFAULT 0,
    latency_6 BIGINT NOT NULL DEFAULT 0,
    latency_7 BIGINT NOT NULL DEFAULT 0,
    latency_8 BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_api_metric_bucket UNIQUE (slot, endpoint)
);

-- 기간 조회(오늘 0시~지금 칸 번호 범위)에 맞춘 인덱스.
CREATE INDEX idx_api_metric_bucket_bucket ON api_metric_bucket (bucket);
