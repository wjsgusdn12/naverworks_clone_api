CREATE TABLE company (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_company_name UNIQUE (name)
);

CREATE TABLE department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_department_company FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT uk_department_company_name UNIQUE (company_id, name)
);

CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_account_email UNIQUE (email)
);

CREATE TABLE membership (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    user_account_id BIGINT NOT NULL,
    department_id BIGINT,
    role VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_membership_company FOREIGN KEY (company_id) REFERENCES company (id),
    CONSTRAINT fk_membership_user_account FOREIGN KEY (user_account_id) REFERENCES user_account (id),
    CONSTRAINT fk_membership_department FOREIGN KEY (department_id) REFERENCES department (id),
    CONSTRAINT uk_membership_company_user_account UNIQUE (company_id, user_account_id),
    CONSTRAINT ck_membership_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_id UUID NOT NULL,
    membership_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_refresh_token_membership FOREIGN KEY (membership_id) REFERENCES membership (id),
    CONSTRAINT uk_refresh_token_token_id UNIQUE (token_id),
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_department_company_id ON department (company_id);
CREATE INDEX idx_membership_user_account_id ON membership (user_account_id);
CREATE INDEX idx_refresh_token_membership_id ON refresh_token (membership_id);
CREATE INDEX idx_refresh_token_expires_at ON refresh_token (expires_at);
