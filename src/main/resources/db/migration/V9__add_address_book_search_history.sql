-- 사용자별 최근 주소록 검색어. 같은 키워드는 최신 시각만 갱신.
CREATE TABLE address_book_search_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_membership_id BIGINT NOT NULL,
    keyword VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_address_book_search_history_owner FOREIGN KEY (owner_membership_id) REFERENCES membership (id),
    CONSTRAINT uk_address_book_search_history_owner_keyword UNIQUE (owner_membership_id, keyword)
);

CREATE INDEX idx_address_book_search_history_owner_updated
    ON address_book_search_history (owner_membership_id, updated_at DESC);

